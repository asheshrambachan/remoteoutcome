test_that("cv.rsv runs on binary outcome data", {
  dat <- sim_rsv_data(n_e = 200, n_o = 400, tau = 0.10, seed = 42)
  R   <- as.matrix(dat[, paste0("R", 1:5)])

  fit <- cv.rsv(
    Y        = dat$Y,
    D        = dat$D,
    S_e      = dat$S_e,
    S_o      = dat$S_o,
    R        = R,
    y_levels = c(0L, 1L),
    yK       = 0L,
    models   = list(
      Y   = list(model = "logit"),
      D   = list(model = "logit"),
      S_e = list(model = "logit"),
      S_o = list(model = "logit")
    ),
    nfolds = 2,
    seed   = 1
  )

  expect_s3_class(fit, "cv.rsv")
  expect_true(is.numeric(fit$coefficients))
  expect_length(fit$coefficients, 1)
  expect_true(is.finite(fit$coefficients))
  expect_equal(fit$n.exp, 200)
  expect_equal(fit$n.obs, 400)
})

