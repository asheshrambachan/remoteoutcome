test_that("add_se with score_bootstrap returns finite SE", {
  dat <- sim_rsv_data(n_e = 200, n_o = 400, tau = 0.10, seed = 20)
  R   <- as.matrix(dat[, paste0("R", 1:5)])

  fit <- cv.rsv(
    Y        = dat$Y,
    D        = dat$D,
    S_e      = dat$S_e,
    S_o      = dat$S_o,
    R        = R,
    y_levels = c(0L, 1L),
    yK       = 0L,
    models   = list(
      Y   = list(model = "logit"),
      D   = list(model = "logit"),
      S_e = list(model = "logit"),
      S_o = list(model = "logit")
    ),
    nfolds = 2,
    seed   = 4
  )

  fit_se <- add_se(fit, method = "score_bootstrap", B = 25, num.threads = 1)

  expect_true(is.finite(fit_se$se))
  expect_gt(fit_se$se, 0)
  # kappa diagnostics exist as numeric fields; may be NA if J is ill-conditioned
  expect_true(is.numeric(fit_se$cond_J_median))
  expect_true(is.numeric(fit_se$cond_J_max))
})

